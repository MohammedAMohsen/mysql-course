-- Lesson 41 - Logical Operators - And, Or, Xor, Not
-- Video: https://www.youtube.com/watch?v=2rXwrlrGRKc

-- Logical Operators:

-- AND  &&  : [ A-Condition + B-Condition ]                 -- لازم الشرطان يتحققان
-- NOT  !   : [ Negative ]                                  -- يعكس الجواب
-- OR   ||  : [ A-Condition Or B-Condition Or Both ]        -- شرط واحد يكفي
-- XOR      : [ A And Not B ] Or [ B And Not A ]            -- شرط واحد فقط، وليس الاثنين معا

-- ملاحظة: العلامتان && و || قديمتان ومهملة في الإصدارات الحديثة، والأفضل استخدام الكلمات AND و OR

-- ==========================================================

-- تجهيز
CREATE DATABASE IF NOT EXISTS test;
USE test;
DROP TABLE IF EXISTS try;
CREATE TABLE try(id INT UNIQUE AUTO_INCREMENT, name VARCHAR(255), date DATETIME, number INT);
INSERT INTO try(name, date, number) VALUES
    ('Mohammed', '2017-04-24 16:10:42', 1),
    ('Mostafa', '2021-01-19 02:40:25', 2),
    ('Albasha', '2019-10-01 11:00:00', 3),
    ('Gamal', '2024-04-03 00:00:00', 4),
    ('Shamah', '2026-04-18 12:51:06', 5),
    ('Marwa', '2025-05-03 00:00:00', 6);
INSERT INTO try(name, date, number) VALUES
    ('Maha', '2026-04-19 00:00:00', 2),
    ('Mal', '2026-04-19 00:00:00', 8),
    ('Mh', '2026-04-19 14:23:22', 1),
    ('Sameh', '2026-04-19 14:32:10', 11),
    ('Samah', '2026-04-19 14:32:18', 11);
DELETE FROM try WHERE id = 5; -- حذفت الصف رقم 5 قبل هذا الدرس

SELECT * FROM try WHERE number = 2;

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  7 | Maha    | 2026-04-19 00:00:00 |      2 |
-- +----+---------+---------------------+--------+

-- -----------------------------

SELECT * FROM try WHERE number = 2 AND name LIKE '%aha';
SELECT * FROM try WHERE number = 2 AND id > 5;

-- +----+------+---------------------+--------+
-- | id | name | date                | number |
-- +----+------+---------------------+--------+
-- |  7 | Maha | 2026-04-19 00:00:00 |      2 |
-- +----+------+---------------------+--------+

-- الاستعلامان يعطيان نفس الناتج

-- -----------------------------

SELECT * FROM try WHERE number = 2 AND id > 7;

-- Empty set

-- لازم الشرطان يتحققان لنجاح الاستعلام، وهنا لا يوجد صف يحقق الاثنين

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE NOT number < 7;

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- |  8 | Mal   | 2026-04-19 00:00:00 |      8 |
-- | 10 | Sameh | 2026-04-19 14:32:10 |     11 |
-- | 11 | Samah | 2026-04-19 14:32:18 |     11 |
-- +----+-------+---------------------+--------+

-- النفي يعكس الجواب، كأني أقول: بدي الأعداد التي ليست أقل من 7

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE number = 2 OR id > 7;

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  7 | Maha    | 2026-04-19 00:00:00 |      2 |
-- |  8 | Mal     | 2026-04-19 00:00:00 |      8 |
-- |  9 | Mh      | 2026-04-19 14:23:22 |      1 |
-- | 10 | Sameh   | 2026-04-19 14:32:10 |     11 |
-- | 11 | Samah   | 2026-04-19 14:32:18 |     11 |
-- +----+---------+---------------------+--------+

-- سواء الشرط الأول تحقق، أو الشرط الثاني، أو الاثنان معا، يظهر الصف
-- لاحظ جاب الصفوف التي رقمها 2، وكمان الصفوف التي id أكبر من 7

-- -----------------------------

SELECT * FROM try WHERE number = 2 OR id > 100;

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  7 | Maha    | 2026-04-19 00:00:00 |      2 |
-- +----+---------+---------------------+--------+

-- شرط واحد تحقق

-- ------------------------------

SELECT * FROM try WHERE number = 50 OR id > 100;

-- Empty set

-- ولا شرط تحقق

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE number = 2 XOR id > 100;

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  7 | Maha    | 2026-04-19 00:00:00 |      2 |
-- +----+---------+---------------------+--------+

-- أحد الشرطين تحقق، وهو المطلوب في XOR

-- ------------------------------

SELECT * FROM try WHERE number = 100 XOR id > 8;

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- |  9 | Mh    | 2026-04-19 14:23:22 |      1 |
-- | 10 | Sameh | 2026-04-19 14:32:10 |     11 |
-- | 11 | Samah | 2026-04-19 14:32:18 |     11 |
-- +----+-------+---------------------+--------+

-- ──────────────────────────────────────────────────────────

-- -------- هذا المثال يبين الفرق بين OR و XOR --------

SELECT * FROM try WHERE number = 1 OR id = 1;

-- +----+----------+---------------------+--------+
-- | id | name     | date                | number |
-- +----+----------+---------------------+--------+
-- |  1 | Mohammed | 2017-04-24 16:10:42 |      1 |
-- |  9 | Mh       | 2026-04-19 14:23:22 |      1 |
-- +----+----------+---------------------+--------+

-- الصف رقم 1 تحقق فيه الشرطان معا، والصف رقم 9 تحقق فيه الشرط الأول فقط
-- و OR تقبل الاثنين

SELECT * FROM try WHERE number = 1 XOR id = 1;

-- +----+------+---------------------+--------+
-- | id | name | date                | number |
-- +----+------+---------------------+--------+
-- |  9 | Mh   | 2026-04-19 14:23:22 |      1 |
-- +----+------+---------------------+--------+

-- أما XOR فتقبل الصف فقط إذا تحقق فيه شرط واحد بالضبط
-- الصف رقم 1 تحقق فيه الشرطان معا، لذلك استبعدته
-- والصف رقم 9 تحقق فيه شرط واحد فقط (number = 1)، لذلك ظهر
