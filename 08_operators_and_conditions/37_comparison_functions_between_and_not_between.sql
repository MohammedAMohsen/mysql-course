-- Lesson 37 - Comparison Functions - Between And Not Between
-- Video: https://www.youtube.com/watch?v=YHR6js9eHHQ

-- Comparison Function Syntax:

-- BETWEEN Min AND Max
-- NOT BETWEEN Min AND Max

-- BETWEEN Min AND Max تعني: Min <= Value AND Value <= Max
-- يعني القيمتان على الأطراف داخلتان في النتيجة

-- ===============================================================

-- تجهيز
CREATE DATABASE IF NOT EXISTS test;
USE test;
DROP TABLE IF EXISTS try;
CREATE TABLE try(id INT UNIQUE AUTO_INCREMENT, name VARCHAR(255), date DATETIME, number INT);
INSERT INTO try(name, date, number) VALUES
    ('Mohammed', '2017-04-24 16:10:42', 1),
    ('Mostafa', '2021-01-19 02:40:25', 2),
    ('Albasha', '2019-10-01 11:00:00', 3),
    ('Gamal', '2024-04-03 00:00:00', 4),
    ('Shamah', '2026-04-18 12:51:06', 5),
    ('Marwa', '2025-05-03 00:00:00', 6);

SELECT * FROM try;

-- +----+----------+---------------------+--------+
-- | id | name     | date                | number |
-- +----+----------+---------------------+--------+
-- |  1 | Mohammed | 2017-04-24 16:10:42 |      1 |
-- |  2 | Mostafa  | 2021-01-19 02:40:25 |      2 |
-- |  3 | Albasha  | 2019-10-01 11:00:00 |      3 |
-- |  4 | Gamal    | 2024-04-03 00:00:00 |      4 |
-- |  5 | Shamah   | 2026-04-18 12:51:06 |      5 |
-- |  6 | Marwa    | 2025-05-03 00:00:00 |      6 |
-- +----+----------+---------------------+--------+

-- ──────────────────────────────────────────────────────────

-- أريد اختيار الصفوف التي رقمها بين 2 و 5

SELECT * FROM try WHERE number BETWEEN 2 AND 5;

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  3 | Albasha | 2019-10-01 11:00:00 |      3 |
-- |  4 | Gamal   | 2024-04-03 00:00:00 |      4 |
-- |  5 | Shamah  | 2026-04-18 12:51:06 |      5 |
-- +----+---------+---------------------+--------+

-- أريد اختيار الصفوف التي رقمها ليس بين 2 و 5

SELECT * FROM try WHERE number NOT BETWEEN 2 AND 5;

-- +----+----------+---------------------+--------+
-- | id | name     | date                | number |
-- +----+----------+---------------------+--------+
-- |  1 | Mohammed | 2017-04-24 16:10:42 |      1 |
-- |  6 | Marwa    | 2025-05-03 00:00:00 |      6 |
-- +----+----------+---------------------+--------+

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE number BETWEEN 2 AND 1;

-- Empty set

-- انتبه للترتيب: لازم القيمة الأولى تكون أصغر من القيمة الثانية، وإلا لن يرجع أي نتيجة

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE date BETWEEN '2024-04-03' AND '2025-05-03';

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- |  4 | Gamal | 2024-04-03 00:00:00 |      4 |
-- |  6 | Marwa | 2025-05-03 00:00:00 |      6 |
-- +----+-------+---------------------+--------+

-- لاحظ الصف رقم 5 ما ظهر لأن تاريخه في 2026، وهو ليس ضمن الفترة

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE date BETWEEN '2019-10-01' AND '2026-04-18';

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  3 | Albasha | 2019-10-01 11:00:00 |      3 |
-- |  4 | Gamal   | 2024-04-03 00:00:00 |      4 |
-- |  6 | Marwa   | 2025-05-03 00:00:00 |      6 |
-- +----+---------+---------------------+--------+

-- يتعامل مع فترة زمنية: أي تاريخ بين التاريخين يظهر في الاستعلام
-- لكن لاحظ الصف رقم 5 (2026-04-18 12:51:06) ما ظهر رغم أن يومه هو آخر يوم في الفترة
-- السبب: التاريخ '2026-04-18' بدون وقت يعني بداية اليوم 00:00:00، والصف بعدها بساعات

-- ──────────────────────────────────────────────────────────

-- نثبت الوقت الحالي على وقت تسجيل الدرس. احذف السطر لترى النتائج حسب تاريخ اليوم
SET TIMESTAMP = UNIX_TIMESTAMP('2026-04-18 13:00:00');

SELECT * FROM try WHERE date BETWEEN DATE_SUB(CURDATE(), INTERVAL 2 MONTH) AND CURDATE();

-- Empty set

-- هات المستخدمين من قبل شهرين حتى الآن، لكنه لم يجد أحدا. لماذا؟

-- DATE_SUB(CURDATE(), INTERVAL 2 MONTH) = 2026-02-18 00:00:00
-- CURDATE() = 2026-04-18 00:00:00

-- الصف رقم 5 تاريخه مع الوقت [2026-04-18 12:51:06]، وهو بعد نهاية الفترة
-- عشان هيك ما ظهر عندي في النتائج
-- الحل: استخدام CURRENT_TIMESTAMP الذي يحسب التاريخ مع الوقت

SELECT * FROM try WHERE date BETWEEN DATE_SUB(CURRENT_TIMESTAMP(), INTERVAL 2 MONTH) AND CURRENT_TIMESTAMP();

-- +----+--------+---------------------+--------+
-- | id | name   | date                | number |
-- +----+--------+---------------------+--------+
-- |  5 | Shamah | 2026-04-18 12:51:06 |      5 |
-- +----+--------+---------------------+--------+

-- يفضل استخدام CURRENT_TIMESTAMP بدل CURDATE، لأن التواريخ في الأغلب تسجل مع الوقت
-- وعشان آخذ بعين الاعتبار الوقت، وما يكون عندي قصور في الاستعلام

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE date BETWEEN DATE_SUB(CURRENT_TIMESTAMP(), INTERVAL 2 YEAR) AND CURRENT_TIMESTAMP();

-- +----+--------+---------------------+--------+
-- | id | name   | date                | number |
-- +----+--------+---------------------+--------+
-- |  5 | Shamah | 2026-04-18 12:51:06 |      5 |
-- |  6 | Marwa  | 2025-05-03 00:00:00 |      6 |
-- +----+--------+---------------------+--------+

-- هات المستخدمين من قبل سنتين حتى الآن

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE date BETWEEN DATE_SUB(CURRENT_TIMESTAMP(), INTERVAL 6 YEAR) AND CURRENT_TIMESTAMP();

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  4 | Gamal   | 2024-04-03 00:00:00 |      4 |
-- |  5 | Shamah  | 2026-04-18 12:51:06 |      5 |
-- |  6 | Marwa   | 2025-05-03 00:00:00 |      6 |
-- +----+---------+---------------------+--------+

SET TIMESTAMP = DEFAULT;
