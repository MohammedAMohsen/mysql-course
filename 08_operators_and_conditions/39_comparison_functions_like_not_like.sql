-- Lesson 39 - Comparison Functions - Like, Not Like
-- Video: https://www.youtube.com/watch?v=rQPccnItU3g

-- Comparison Function Syntax:

-- LIKE: يشبه. قريبة من فكرة يساوي، لكنها تسمح بالبحث عن نمط وليس قيمة كاملة فقط

-- %  (لا شيء أو مجموعة من الحروف)
-- _  (حرف واحد بالضبط)

-- NOT LIKE: نفس الشيء مع نفس الرموز السابقة، لكن الناتج يكون العكس (لا يشبه)

-- ملاحظة: البحث هنا لا يفرق بين الحروف الكبيرة والصغيرة، بسبب نوع الترتيب الافتراضي للجدول

-- ============================================================

-- تجهيز: الجدول بعد إضافة صفوف جديدة
CREATE DATABASE IF NOT EXISTS test;
USE test;
DROP TABLE IF EXISTS try;
CREATE TABLE try(id INT UNIQUE AUTO_INCREMENT, name VARCHAR(255), date DATETIME, number INT);
INSERT INTO try(name, date, number) VALUES
    ('Mohammed', '2017-04-24 16:10:42', 1),
    ('Mostafa', '2021-01-19 02:40:25', 2),
    ('Albasha', '2019-10-01 11:00:00', 3),
    ('Gamal', '2024-04-03 00:00:00', 4),
    ('Shamah', '2026-04-18 12:51:06', 5),
    ('Marwa', '2025-05-03 00:00:00', 6);
INSERT INTO try(name, date, number) VALUES
    ('Maha', '2026-04-19 00:00:00', 2),
    ('Mal', '2026-04-19 00:00:00', 8),
    ('Mh', '2026-04-19 14:23:22', 1),
    ('Sameh', '2026-04-19 14:32:10', 11),
    ('Samah', '2026-04-19 14:32:18', 11);
DELETE FROM try WHERE id = 5; -- حذفت الصف رقم 5 قبل هذا الدرس

SELECT * FROM try WHERE name LIKE 'Maha';

-- +----+------+---------------------+--------+
-- | id | name | date                | number |
-- +----+------+---------------------+--------+
-- |  7 | Maha | 2026-04-19 00:00:00 |      2 |
-- +----+------+---------------------+--------+

-- أي سجل في عمود الاسم يشبه 'Maha' تماما

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE 'aha';

-- Empty set

-- ------------------

SELECT * FROM try WHERE name LIKE '%aha';

-- +----+------+---------------------+--------+
-- | id | name | date                | number |
-- +----+------+---------------------+--------+
-- |  7 | Maha | 2026-04-19 00:00:00 |      2 |
-- +----+------+---------------------+--------+

-- أي سجل في عمود الاسم ينتهي بـ 'aha'، وقبله لا شيء أو أي عدد من الحروف

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE '%mal';

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- |  4 | Gamal | 2024-04-03 00:00:00 |      4 |
-- |  8 | Mal   | 2026-04-19 00:00:00 |      8 |
-- +----+-------+---------------------+--------+

-- أي سجل ينتهي بـ 'mal'، وقبله لا شيء أو أي حروف

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE 'Gam%';

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- |  4 | Gamal | 2024-04-03 00:00:00 |      4 |
-- +----+-------+---------------------+--------+

-- أي سجل يبدأ بـ 'Gam'، وبعده لا شيء أو أي حروف

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name NOT LIKE 'M%';

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  3 | Albasha | 2019-10-01 11:00:00 |      3 |
-- |  4 | Gamal   | 2024-04-03 00:00:00 |      4 |
-- | 10 | Sameh   | 2026-04-19 14:32:10 |     11 |
-- | 11 | Samah   | 2026-04-19 14:32:18 |     11 |
-- +----+---------+---------------------+--------+

-- أي اسم لا يبدأ بالحرف M

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE '%ama%';

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- |  4 | Gamal | 2024-04-03 00:00:00 |      4 |
-- | 11 | Samah | 2026-04-19 14:32:18 |     11 |
-- +----+-------+---------------------+--------+

-- أي اسم يحتوي على 'ama' في أي مكان

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE 'M%a';

-- +----+---------+---------------------+--------+
-- | id | name    | date                | number |
-- +----+---------+---------------------+--------+
-- |  2 | Mostafa | 2021-01-19 02:40:25 |      2 |
-- |  6 | Marwa   | 2025-05-03 00:00:00 |      6 |
-- |  7 | Maha    | 2026-04-19 00:00:00 |      2 |
-- +----+---------+---------------------+--------+

-- أي اسم يبدأ بالحرف M وينتهي بالحرف a

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE 'M%h%';

-- +----+----------+---------------------+--------+
-- | id | name     | date                | number |
-- +----+----------+---------------------+--------+
-- |  1 | Mohammed | 2017-04-24 16:10:42 |      1 |
-- |  7 | Maha     | 2026-04-19 00:00:00 |      2 |
-- |  9 | Mh       | 2026-04-19 14:23:22 |      1 |
-- +----+----------+---------------------+--------+

-- أي اسم يبدأ بالحرف M ويحتوي على الحرف h، وقبل الحرف h وبعده أي حروف أو لا شيء

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE '_mal';

-- Empty set

-- أي اسم من 4 حروف: حرف واحد أي حرف، ثم 'mal'

-- ------------------

SELECT * FROM try WHERE name LIKE '__mal';

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- |  4 | Gamal | 2024-04-03 00:00:00 |      4 |
-- +----+-------+---------------------+--------+

-- أي اسم من 5 حروف: حرفان أي حرفين، ثم 'mal'

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE 'Sam_h';

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- | 10 | Sameh | 2026-04-19 14:32:10 |     11 |
-- | 11 | Samah | 2026-04-19 14:32:18 |     11 |
-- +----+-------+---------------------+--------+

-- أي اسم يبدأ بـ 'Sam' وينتهي بالحرف h، وبينهما حرف واحد فقط

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE '%am_h';

-- +----+-------+---------------------+--------+
-- | id | name  | date                | number |
-- +----+-------+---------------------+--------+
-- | 10 | Sameh | 2026-04-19 14:32:10 |     11 |
-- | 11 | Samah | 2026-04-19 14:32:18 |     11 |
-- +----+-------+---------------------+--------+

-- نفس الفكرة السابقة مع %: قبل 'am' لا شيء أو أي حروف

-- ──────────────────────────────────────────────────────────

SELECT * FROM try WHERE name LIKE '%_%';

-- +----+----------+---------------------+--------+
-- | id | name     | date                | number |
-- +----+----------+---------------------+--------+
-- |  1 | Mohammed | 2017-04-24 16:10:42 |      1 |
-- |  2 | Mostafa  | 2021-01-19 02:40:25 |      2 |
-- |  3 | Albasha  | 2019-10-01 11:00:00 |      3 |
-- |  4 | Gamal    | 2024-04-03 00:00:00 |      4 |
-- |  6 | Marwa    | 2025-05-03 00:00:00 |      6 |
-- |  7 | Maha     | 2026-04-19 00:00:00 |      2 |
-- |  8 | Mal      | 2026-04-19 00:00:00 |      8 |
-- |  9 | Mh       | 2026-04-19 14:23:22 |      1 |
-- | 10 | Sameh    | 2026-04-19 14:32:10 |     11 |
-- | 11 | Samah    | 2026-04-19 14:32:18 |     11 |
-- +----+----------+---------------------+--------+

-- أي اسم فيه حرف واحد على الأقل، يعني كل الأسماء غير الفارغة
