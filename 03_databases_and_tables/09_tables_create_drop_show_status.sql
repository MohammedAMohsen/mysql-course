-- ===================================================================

-- CREATE TABLE students;
-- ERROR 4028 (HY000): A table must have at least one visible column.

-- الجدول لازم يكون فيه عمود واحد على الأقل

-- ===================================================================

CREATE TABLE IF NOT EXISTS students( -- إنشاء جدول الطلاب إذا لم يكن موجودا
    id INT,
    name VARCHAR(255),
    email VARCHAR(255)
);

-- ممكن أكتبه بالطريقة السابقة أو على سطر واحد مثل الطريقة التالية
-- وبما أن الجدول موجود، الأمر التالي لا يفعل شيئا ولا يعطي خطأ بفضل IF NOT EXISTS

CREATE TABLE IF NOT EXISTS students(id INT, name VARCHAR(255), email VARCHAR(255));

-- ملاحظة: في الإصدارات القديمة كنا نكتب INT(11)، والرقم بين القوسين لا يحدد حجم الرقم
-- هو فقط عرض للأرقام عند العرض، ومن الإصدار 8 لم يعد مستخدما، لذلك يظهر النوع int فقط

-- ===================================================================

-- بعد ما أنشأت الجدول بدي أعرض الأعمدة الخاصة فيه: أسماء الأعمدة ونوع كل عمود وهكذا
-- هناك ثلاث طرق (أوامر) وكلها تعطي نفس الناتج

DESCRIBE students; -- الطريقة الأولى

-- +-------+--------------+------+-----+---------+-------+
-- | Field | Type         | Null | Key | Default | Extra |
-- +-------+--------------+------+-----+---------+-------+
-- | id    | int          | YES  |     | NULL    |       |
-- | name  | varchar(255) | YES  |     | NULL    |       |
-- | email | varchar(255) | YES  |     | NULL    |       |
-- +-------+--------------+------+-----+---------+-------+

SHOW COLUMNS FROM students; -- الطريقة الثانية

-- +-------+--------------+------+-----+---------+-------+
-- | Field | Type         | Null | Key | Default | Extra |
-- +-------+--------------+------+-----+---------+-------+
-- | id    | int          | YES  |     | NULL    |       |
-- | name  | varchar(255) | YES  |     | NULL    |       |
-- | email | varchar(255) | YES  |     | NULL    |       |
