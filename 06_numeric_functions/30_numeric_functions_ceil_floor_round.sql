-- Lesson 30 - Numeric Functions - Ceil, Floor, Round
-- Video: https://www.youtube.com/watch?v=l0Wi9OlY6sk

-- MySQL Numeric Functions Syntax:

-- CEIL(Number)  -- سقف: يقرب الرقم لأقرب عدد صحيح من فوق (للقيمة الأعلى)
-- FLOOR(Number) -- أرضية: يقرب الرقم لأقرب عدد صحيح من تحت (للقيمة الأدنى)

-- ROUND(Number, Decimal)
-- يقرب للأقرب: إذا كان الرقم بعد الفاصلة 5 أو أكثر يقرب للأعلى، وإذا كان 4 أو أقل يقرب للأدنى
-- Decimal: عدد الأرقام بعد الفاصلة التي يعرضها ويقرب عليها، والقيمة الافتراضية 0
-- مثال: ROUND(1.55, 1) = 1.6

-- ===========================================================================

-- تجهيز
CREATE DATABASE IF NOT EXISTS test;
USE test;
DROP TABLE IF EXISTS try;
CREATE TABLE try(id INT UNIQUE AUTO_INCREMENT, number DOUBLE);
INSERT INTO try(number) VALUES(1.2), (1.45), (1.55), (1.99), (1.456789);

SELECT * FROM try;

-- +----+----------+
-- | id | number   |
-- +----+----------+
-- |  1 |      1.2 |
-- |  2 |     1.45 |
-- |  3 |     1.55 |
-- |  4 |     1.99 |
-- |  5 | 1.456789 |
-- +----+----------+

-- --------------------------------

SELECT number, CEIL(number) AS CeilNumber FROM try;

-- +----------+------------+
-- | number   | CeilNumber |
-- +----------+------------+
-- |      1.2 |          2 |
-- |     1.45 |          2 |
-- |     1.55 |          2 |
-- |     1.99 |          2 |
-- | 1.456789 |          2 |
-- +----------+------------+

-- --------------------------------

SELECT number, FLOOR(number) AS FloorNumber FROM try;

-- +----------+-------------+
-- | number   | FloorNumber |
-- +----------+-------------+
-- |      1.2 |           1 |
-- |     1.45 |           1 |
-- |     1.55 |           1 |
-- |     1.99 |           1 |
-- | 1.456789 |           1 |
-- +----------+-------------+

-- --------------------------------

SELECT number, ROUND(number) AS RoundNumber FROM try;

-- +----------+-------------+
-- | number   | RoundNumber |
-- +----------+-------------+
-- |      1.2 |           1 |
-- |     1.45 |           1 |
-- |     1.55 |           2 |
-- |     1.99 |           2 |
-- | 1.456789 |           1 |
-- +----------+-------------+

-- --------------------------------

SELECT number, ROUND(number, 1) AS RoundNumber FROM try;

-- +----------+-------------+
-- | number   | RoundNumber |
-- +----------+-------------+
-- |      1.2 |         1.2 |
-- |     1.45 |         1.4 |
-- |     1.55 |         1.6 |
-- |     1.99 |           2 |
-- | 1.456789 |         1.5 |
-- +----------+-------------+

-- انتبه للرقم 1.45: النوع DOUBLE يحفظ الأرقام بشكل تقريبي
-- فالرقم 1.45 محفوظ فعليا كرقم أصغر بقليل، مثل 1.4499999، لذلك قربه إلى 1.4
-- لو كان العمود من النوع DECIMAL لكان الناتج 1.5، لأن DECIMAL يحفظ الرقم بدقة

SELECT ROUND(1.45, 1) AS decimal_round;

-- +---------------+
-- | decimal_round |
-- +---------------+
-- |           1.5 |
-- +---------------+

-- الرقم المكتوب مباشرة في الاستعلام يعامل كـ DECIMAL، لذلك أعطى 1.5

-- ---------------------------------

SELECT number, ROUND(number, 2) AS RoundNumber FROM try;

-- +----------+-------------+
-- | number   | RoundNumber |
-- +----------+-------------+
-- |      1.2 |         1.2 |
-- |     1.45 |        1.45 |
-- |     1.55 |        1.55 |
-- |     1.99 |        1.99 |
-- | 1.456789 |        1.46 |
-- +----------+-------------+
